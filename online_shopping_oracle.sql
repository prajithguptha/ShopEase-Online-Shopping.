-- ShopEasy Online Shopping System - Oracle SQL
-- Run as a schema user with CREATE TABLE and CREATE SEQUENCE privileges.
-- Re-running this whole script will report "already exists" errors for existing objects.
SET DEFINE OFF;

CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR2(100) NOT NULL,
    email       VARCHAR2(120) NOT NULL UNIQUE,
    phone       VARCHAR2(15),
    created_at  DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE categories (
    category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  NUMBER NOT NULL,
    product_name VARCHAR2(120) NOT NULL,
    description  VARCHAR2(300),
    price        NUMBER(10,2) NOT NULL CHECK (price >= 0),
    stock_qty    NUMBER(8) DEFAULT 0 NOT NULL CHECK (stock_qty >= 0),
    active       CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories(category_id)
);

CREATE TABLE orders (
    order_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER NOT NULL,
    order_date  DATE DEFAULT SYSDATE NOT NULL,
    status      VARCHAR2(20) DEFAULT 'PLACED' NOT NULL
        CHECK (status IN ('PLACED','PAID','SHIPPED','DELIVERED','CANCELLED')),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL,
    product_id    NUMBER NOT NULL,
    quantity      NUMBER(8) NOT NULL CHECK (quantity > 0),
    unit_price    NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT fk_items_order FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT uq_order_product UNIQUE (order_id, product_id)
);

