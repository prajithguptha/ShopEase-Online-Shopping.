CREATE OR REPLACE VIEW product_catalog AS
SELECT p.product_id, p.product_name, c.category_name, p.description, p.price, p.stock_qty
FROM products p
JOIN categories c ON c.category_id = p.category_id
WHERE p.active = 'Y';

CREATE OR REPLACE VIEW order_summary AS
SELECT o.order_id, c.full_name, c.email, o.order_date, o.status,
       SUM(oi.quantity * oi.unit_price) AS order_total
FROM orders o
JOIN customers c ON c.customer_id = o.customer_id
JOIN order_items oi ON oi.order_id = o.order_id
GROUP BY o.order_id, c.full_name, c.email, o.order_date, o.status;

COMMIT;

-- Useful practice queries
-- 1. List available products:
SELECT * FROM product_catalog ORDER BY category_name, product_name;

-- 2. Search products by name:
SELECT * FROM product_catalog WHERE LOWER(product_name) LIKE '%headphone%';

-- 3. Products under ₹1000:
SELECT product_name, price FROM products WHERE price < 1000 ORDER BY price;

-- 4. Total value of each order:
SELECT * FROM order_summary ORDER BY order_date DESC;

-- 5. Total number of products in each category:
SELECT c.category_name, COUNT(p.product_id) AS product_count
FROM categories c LEFT JOIN products p ON p.category_id = c.category_id
GROUP BY c.category_name ORDER BY c.category_name;

